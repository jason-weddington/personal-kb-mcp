# --- turn: request ------------------------------------------------------------


def _write(path: Path, records: list[dict[str, Any]]) -> str:
    path.write_text("\n".join(json.dumps(r) for r in records) + "\n", encoding="utf-8")
    return str(path)


def _prompt(text: str) -> dict[str, Any]:
    return {"type": "user", "uuid": "p", "origin": {"kind": "human"}, "message": {"content": text}}


def _use(i: int, cmd: str) -> dict[str, Any]:
    block = {"type": "tool_use", "id": f"t{i}", "name": "Bash", "input": {"command": cmd}}
    return {"type": "assistant", "uuid": f"a{i}", "message": {"content": [block]}}


def _result(i: int, text: str, is_error: bool = True) -> dict[str, Any]:
    block = {"type": "tool_result", "tool_use_id": f"t{i}", "content": text, "is_error": is_error}
    return {"type": "user", "uuid": f"r{i}", "message": {"content": [block]}}


def _text(text: str) -> dict[str, Any]:
    block = {"type": "text", "text": text}
    return {"type": "assistant", "uuid": "x", "message": {"content": [block]}}


def _thinking() -> dict[str, Any]:
    block = {"type": "thinking", "thinking": "plan"}
    return {"type": "assistant", "uuid": "th", "message": {"content": [block]}}


def _digest(path: Path, records: list[dict[str, Any]]) -> bytes:
    window = turn_digest.read_turn(_write(path, records), None)
    raw = turn_digest.build_digest(
        {"session_id": "s1", "last_assistant_message": "done"},
        turn_index=3,
        project="personal-kb",
        window=window,
    )
    assert raw is not None
    return raw


def _max_length(prop: dict[str, Any]) -> int:
    if "maxLength" in prop:
        return int(prop["maxLength"])
    return next(int(m["maxLength"]) for m in prop["anyOf"] if m.get("type") == "string")


def test_turn_request_matches_fixture(tmp_path: Path) -> None:
    schema = TURN["request"]["schema"]
    mapping = schema["properties"]["items"]["items"]["discriminator"]["mapping"]
    raw = _digest(
        tmp_path / "t.jsonl",
        [
            _prompt("go"),
            _thinking(),
            _text("hi"),
            _use(1, "git push mirror main"),
            _result(1, "denied"),
        ],
    )
    body = json.loads(raw)
    assert Draft202012Validator(schema).is_valid(body)
    assert len(raw) <= TURN["request"]["max_body_bytes"]
    missing = (set(schema["properties"]) - HOOK_OMITTED_REQUEST_FIELDS) - set(body)
    assert not missing, (
        f"request field(s) {sorted(missing)} not sent by the hook; send them in "
        "turn_digest.build_digest or list them in HOOK_OMITTED_REQUEST_FIELDS"
    )
    assert set(body) == set(schema["properties"]) - HOOK_OMITTED_REQUEST_FIELDS
    assert set(schema.get("required", [])) <= set(body)
    assert body["event_id"] == f"{body['session_id']}:{body['turn_index']}"
    for item in body["items"]:
        ref = mapping[item["kind"]].removeprefix("#/$defs/")
        want = set(schema["$defs"][ref]["properties"])
        assert set(item) == want - HOOK_OMITTED_ITEM_FIELDS.get(item["kind"], frozenset())
    assert {i["kind"] for i in body["items"]} == HOOK_ITEM_KINDS
    assert set(mapping) >= HOOK_ITEM_KINDS


def test_turn_truncation_stays_within_limit(tmp_path: Path) -> None:
    records = [_prompt("go")]
    for i in range(60):
        records += [_use(i, f"ls {i}"), _result(i, "r" * 3000)]
    raw = _digest(tmp_path / "t.jsonl", records)
    body = json.loads(raw)
    assert Draft202012Validator(TURN["request"]["schema"]).is_valid(body)
    assert body["truncated"] is True
    assert len(raw) <= TURN["request"]["max_body_bytes"]


def test_turn_caps_match_fixture() -> None:
    schema = TURN["request"]["schema"]
    props = schema["properties"]
    defs = schema["$defs"]
    assert TURN["request"]["max_body_bytes"] == turn_digest.TURN_DIGEST_MAX_BYTES
    assert props["items"]["maxItems"] == turn_digest.TURN_ITEMS_MAX
    assert _max_length(props["user_prompt"]) == turn_digest.TURN_USER_PROMPT_MAX
    assert _max_length(props["final_message"]) == turn_digest.TURN_FINAL_MESSAGE_MAX
    assert (
        defs["TurnAssistantTextItem"]["properties"]["text"]["maxLength"]
        == turn_digest.TURN_TEXT_MAX
    )
    assert (
        defs["TurnToolCallItem"]["properties"]["target"]["maxLength"] == turn_digest.TURN_TARGET_MAX
    )
    assert (
        defs["TurnToolResultItem"]["properties"]["excerpt"]["maxLength"]
        == turn_digest.TURN_EXCERPT_MAX
    )
    modes = PREVENTION["response"]["schema"]["properties"]["surprise_capture"]["enum"]
    assert set(modes) >= turn_digest.SEND_MODES


