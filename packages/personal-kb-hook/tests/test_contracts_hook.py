HOOK_ITEM_KINDS = frozenset({"assistant_text", "tool_call", "tool_result"})
HOOK_OMITTED_REQUEST_FIELDS: frozenset[str] = frozenset()
HOOK_OMITTED_ITEM_FIELDS: dict[str, frozenset[str]] = {}
EXPECTED_SENDER_RESULT: dict[str, str | None] = {
    "recorded": None,
    "duplicate": None,
    "capture-off": None,
    "duplicate-mismatch": "rejected_duplicate-mismatch",
    "redaction-unavailable": "rejected_redaction-unavailable",
    "write-failed": "rejected_write-failed",
}

_CONTRACTS = Path(__file__).resolve().parents[3] / "contracts"
_SID = "contract-session-1"


def _load(name: str) -> dict[str, Any]:
    doc = json.loads((_CONTRACTS / f"{name}.json").read_text(encoding="utf-8"))
    assert isinstance(doc, dict)
    return doc


PREVENTION = _load("prevention")
TURN = _load("turn")
RESPONSE_EXAMPLES = PREVENTION["response"]["examples"]
TURN_RESPONSE_EXAMPLES = TURN["response"]["examples"]


class _Resp:
    def __init__(self, status: int = 200, body: bytes = b"{}") -> None:
        self.status = status
        self._body = body

    def getcode(self) -> int:
        return self.status

    def read(self) -> bytes:
        return self._body

    def __enter__(self) -> _Resp:
        return self

    def __exit__(self, *args: object) -> None:
        return None


class _Server:
    """Fake urlopen: records every Request and answers with ``body``."""

    def __init__(self) -> None:
        self.requests: list[Any] = []
        self.body: bytes = b"{}"

    def __call__(self, req: Any, timeout: float = 30.0) -> _Resp:
        self.requests.append(req)
        return _Resp(200, self.body)


