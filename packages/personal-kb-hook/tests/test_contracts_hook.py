def _start_payload(tmp_path: Path) -> dict[str, Any]:
    repo = tmp_path / "git" / "personal_kb"
    repo.mkdir(parents=True)
    (repo / ".kb_project").write_text("personal-kb\n", encoding="utf-8")
    return {
        "hook_event_name": "SessionStart",
        "session_id": _SID,
        "cwd": str(repo),
        "source": "startup",
    }


def _body(name: str) -> dict[str, Any]:
    return next(e["body"] for e in RESPONSE_EXAMPLES if e["name"] == name)


def _pre(command: str, tool_use_id: str) -> dict[str, Any]:
    return {
        "hook_event_name": "PreToolUse",
        "session_id": _SID,
        "tool_name": "Bash",
        "tool_use_id": tool_use_id,
        "tool_input": {"command": command},
    }


def _cache() -> dict[str, Any]:
    return json.loads(paths.get_prevention_cache_path(_SID).read_text())


def _reason(raw: str | None) -> str:
    assert raw is not None
    out = json.loads(raw)["hookSpecificOutput"]
    assert out["permissionDecision"] == "deny"
    return str(out["permissionDecisionReason"])


