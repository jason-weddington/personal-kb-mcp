def test_sender_classifies_every_server_reason() -> None:
    reasons = set(TURN["response"]["schema"]["properties"]["reason"]["enum"])
    unclassified = sorted(reasons - set(EXPECTED_SENDER_RESULT))
    stale = sorted(set(EXPECTED_SENDER_RESULT) - reasons)
    assert not unclassified and not stale, (
        f"unclassified reason(s) {unclassified}, stale {stale}: classify each in "
        "turn_sender.REJECT_REASONS and in EXPECTED_SENDER_RESULT"
    )
    rejected = {r for r, v in EXPECTED_SENDER_RESULT.items() if v is not None}
    assert set(turn_sender.REJECT_REASONS) == rejected


@pytest.mark.parametrize(
    "example", TURN_RESPONSE_EXAMPLES, ids=[e["name"] for e in TURN_RESPONSE_EXAMPLES]
)
def test_sender_handles_response_example(
    example: dict[str, Any], tmp_path: Path, server: _Server
) -> None:
    request = next(
        e["body"] for e in TURN["request"]["examples"] if e["name"] == "claude_code_turn"
    )
    path = tmp_path / f"body-{example['name']}.json"
    path.write_text(json.dumps(request), encoding="utf-8")
    server.body = json.dumps(example["body"]).encode()
    result = turn_sender.send_file(str(path), "s1")
    assert result == EXPECTED_SENDER_RESULT[example["name"]]
    assert not path.exists()
    (req,) = server.requests
    assert req.get_method() == "POST"
    assert urllib.parse.urlsplit(req.full_url).path == TURN["path"]
    assert req.get_header("Content-type") == "application/json"
    rows = [
        json.loads(line) for line in paths.get_turn_digest_log_path("s1").read_text().splitlines()
    ]
    assert rows[-1]["server_reason"] == example["body"]["reason"]
    assert rows[-1]["redactions"] == len(example["body"]["redactions"])
