def test_prevention_request_matches_fixture(tmp_path: Path, server: _Server) -> None:
    server.body = json.dumps(_body("gate_armed")).encode()
    prevention.session_start(_start_payload(tmp_path))
    assert len(server.requests) == 1
    req = server.requests[0]
    split = urllib.parse.urlsplit(req.full_url)
    assert req.get_method() == PREVENTION["method"]
    assert split.path == PREVENTION["path"]
    assert req.get_header("Authorization") == "Bearer test-key"
    query = dict(urllib.parse.parse_qsl(split.query, keep_blank_values=True))
    schema = PREVENTION["request"]["query_schema"]
    assert Draft202012Validator(schema).is_valid(query)
    assert set(query) >= set(schema["required"])
    assert query["project"] == "personal-kb"


